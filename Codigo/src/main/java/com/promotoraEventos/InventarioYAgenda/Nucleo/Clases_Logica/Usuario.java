package com.promotoraEventos.InventarioYAgenda.Nucleo.Clases_Logica;

public class Usuario {
    private String m_nombre;
    private String m_contraseña;
    private String m_rol;
    
    public String getNombre() {
        return m_nombre;
    }
    public void setNombre(String m_nombre) {
        this.m_nombre = m_nombre;
    }
    public String getContraseña() {
        return m_contraseña;
    }
    public void setContraseña(String m_contraseña) {
        this.m_contraseña = m_contraseña;
    }
    public String getRol() {
        return m_rol;
    }
    public void setRol(String m_rol) {
        this.m_rol = m_rol;
    }

    

}
